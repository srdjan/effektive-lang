// Generates the standalone typed IR that the website publishes as
// `../effektive/public/typed-ir.ts`. The output is a fixed header, the type
// declarations of `src/core/predicates.ts` that `src/core/ir.ts` needs, and the
// text of `ir.ts` without its import. Run `deno task site:ir` after a change of
// `ir.ts`. `tests/ir_site_slow_test.ts` compares the output with the website file.

/** The names that `ir.ts` imports from `predicates.ts`. */
const ROOTS: readonly string[] = ["Predicate", "ProofCertificate"];

const HEADER = [
  "// Generated from src/core/ir.ts of the effektive-lang repository.",
  "// Do not edit this file. Run `deno task site:ir` in that repository.",
  "",
].join("\n");

const IMPORT_LINE =
  'import type { Predicate, ProofCertificate } from "./predicates.ts";';

export type SiteIrResult =
  | { readonly ok: true; readonly text: string }
  | { readonly ok: false; readonly message: string };

interface TypeBlock {
  readonly name: string;
  /** The declaration with its doc comment, in the form `export type|interface`. */
  readonly text: string;
}

const DECLARATION = /^(?:export )?(type|interface) (\w+)/;

/** The type declarations at the top level of `predicates`, found by blank-line blocks. */
function typeBlocks(predicates: string): readonly TypeBlock[] {
  const blocks: TypeBlock[] = [];
  for (const block of predicates.split(/\n\s*\n/)) {
    const lines = block.split("\n");
    const first = lines.findIndex((line) =>
      !line.startsWith("/**") && !line.startsWith(" *") &&
      !line.startsWith("//")
    );
    const match = first < 0 ? null : DECLARATION.exec(lines[first] ?? "");
    if (match === null) continue;
    const declaration = lines.slice(first).join("\n").replace(
      /^(?:export )?/,
      "export ",
    );
    blocks.push({
      name: match[2] ?? "",
      text: [...lines.slice(0, first), declaration].join("\n"),
    });
  }
  return blocks;
}

/** The text of a block without comments, so a word in a comment adds no dependency. */
function code(block: TypeBlock): string {
  return block.text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
}

/** The blocks that `ROOTS` need, in the order of `blocks`. */
function closure(blocks: readonly TypeBlock[]): Result {
  const needed = new Set<string>();
  const pending = [...ROOTS];
  for (let name = pending.pop(); name !== undefined; name = pending.pop()) {
    if (needed.has(name)) continue;
    const block = blocks.find((candidate) => candidate.name === name);
    if (block === undefined) {
      return { ok: false, message: `predicates.ts declares no type ${name}` };
    }
    needed.add(name);
    for (const other of blocks) {
      if (
        other.name !== name &&
        new RegExp(`\\b${other.name}\\b`).test(code(block))
      ) {
        pending.push(other.name);
      }
    }
  }
  return { ok: true, blocks: blocks.filter((block) => needed.has(block.name)) };
}

type Result =
  | { readonly ok: true; readonly blocks: readonly TypeBlock[] }
  | { readonly ok: false; readonly message: string };

/** Builds the text of the website `typed-ir.ts` from the text of `ir.ts` and `predicates.ts`. */
export function generateSiteIr(ir: string, predicates: string): SiteIrResult {
  if (!ir.startsWith(IMPORT_LINE + "\n")) {
    return {
      ok: false,
      message: "ir.ts does not start with the predicates import",
    };
  }
  const needed = closure(typeBlocks(predicates));
  if (!needed.ok) return needed;
  const declarations = needed.blocks.map((block) => block.text).join("\n\n");
  const body = ir.slice(IMPORT_LINE.length + 1).replace(/^\n+/, "");
  return { ok: true, text: `${HEADER}\n${declarations}\n\n${body}` };
}

if (import.meta.main) {
  const root = new URL("../", import.meta.url);
  const target = new URL(
    Deno.args[0] ?? "../effektive/public/typed-ir.ts",
    root,
  );
  const result = generateSiteIr(
    await Deno.readTextFile(new URL("src/core/ir.ts", root)),
    await Deno.readTextFile(new URL("src/core/predicates.ts", root)),
  );
  if (!result.ok) {
    console.error(`site:ir: ${result.message}`);
    Deno.exit(1);
  }
  await Deno.writeTextFile(target, result.text);
  console.log(`wrote ${target.pathname}`);
}
