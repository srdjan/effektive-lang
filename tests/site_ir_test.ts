import { assert, assertEquals } from "@std/assert";
import { generateSiteIr } from "../scripts/site_ir.ts";

const IMPORT =
  'import type { Predicate, ProofCertificate } from "./predicates.ts";';

const PREDICATES = [
  "/** An integer text. */",
  "type DecimalInteger = string;",
  "",
  "/** A predicate. */",
  "export type Predicate =",
  '  | { readonly kind: "constant"; readonly value: boolean }',
  '  | { readonly kind: "not"; readonly operand: Predicate; readonly bound: DecimalInteger };',
  "",
  "type Comparison = Unused | Other;",
  "",
  "export interface ProofCertificate {",
  "  readonly claim: string;",
  "}",
  "",
  "export function solve(): void {}",
].join("\n");

Deno.test("generateSiteIr writes the header, the needed declarations, and the IR body", () => {
  const result = generateSiteIr(
    `${IMPORT}\n\n// Contract.\nexport type A = Predicate;\n`,
    PREDICATES,
  );
  assert(result.ok);
  assertEquals(
    result.text,
    [
      "// Generated from src/core/ir.ts of the effektive-lang repository.",
      "// Do not edit this file. Run `deno task site:ir` in that repository.",
      "",
      "/** An integer text. */",
      "export type DecimalInteger = string;",
      "",
      "/** A predicate. */",
      "export type Predicate =",
      '  | { readonly kind: "constant"; readonly value: boolean }',
      '  | { readonly kind: "not"; readonly operand: Predicate; readonly bound: DecimalInteger };',
      "",
      "export interface ProofCertificate {",
      "  readonly claim: string;",
      "}",
      "",
      "// Contract.",
      "export type A = Predicate;",
      "",
    ].join("\n"),
  );
});

Deno.test("generateSiteIr rejects an IR without the predicates import", () => {
  assertEquals(generateSiteIr("export type A = 1;\n", PREDICATES), {
    ok: false,
    message: "ir.ts does not start with the predicates import",
  });
});

Deno.test("generateSiteIr rejects predicates without a needed type", () => {
  assertEquals(
    generateSiteIr(`${IMPORT}\nexport type A = 1;\n`, "type X = 1;"),
    {
      ok: false,
      message: "predicates.ts declares no type ProofCertificate",
    },
  );
});
